// The settings screen's texts: one table per language, keyed by the same ids, merged once into a hash map.
//
// The tables are UTF-8 string literals (the source is UTF-8; MSVC needs /utf-8). A key missing from a table, or left
// empty, falls back to English, then to the key: a half-translated language still works, and a key nobody wrote is
// visible on screen instead of blank. "{}" in a text is filled by trf().
